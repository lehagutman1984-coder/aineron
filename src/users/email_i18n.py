def get_email_context(email_type: str, lang: str) -> tuple:
    """
    Возвращает (t, resolved_lang) - словарь строк (common + type-specific,
    слитый) для рендера письма, и итоговый использованный язык (после
    фолбэка на ru). t передаётся в шаблон как {{ t.xxx }}.
    """
    resolved = lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    common = EMAIL_COMMON.get(resolved, EMAIL_COMMON[DEFAULT_LANG])
    specific = EMAIL_TRANSLATIONS[email_type].get(resolved, EMAIL_TRANSLATIONS[email_type][DEFAULT_LANG])
    return {**common, **specific}, resolved
